/*
 * Regenerates database/schema.sql and database/seed-reference.sql from the database in
 * .env (DB_NAME). Run it after applying a new migration so fresh installs and the test
 * database match the real schema:
 *
 *   node database/tools/exportSchema.js
 *
 * schema.sql           every table's CREATE statement (no data).
 * seed-reference.sql   lookup data the app needs to work (countries, cities, shops,
 *                      payment methods, weight brackets, routes, categories…). No people:
 *                      the house broker gets a synthetic contact instead of a real one.
 */
const fs = require('fs');
const path = require('path');
const db = require('../../config/db');

const OUT_DIR = path.join(__dirname, '..');

// Copied in full, in foreign-key order.
const REFERENCE_TABLES = [
  'country', 'region', 'city',
  'paymentmethod', 'mobileoperator', 'creditcardtype',
  'weightlimit', 'volumelimit', 'zone', 'traject',
  'productdivision', 'productline', 'producttype',
  'ratingsimage', 'transportertype', 'suppliertype', 'brokertype', 'clienttype',
  'colorlookup', 'lenghtlookup',
];

// The house broker that purchase orders and promotions are attributed to.
const HOUSE = {
  brokerID: 'BRK_1',
  contactID: 'CNT_SBO',
  addressID: 'ADDR_SBO',
};

const header = (title) => `-- ${title}\n-- Generated by database/tools/exportSchema.js — do not edit by hand.\n\n`;

const sqlValue = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (v instanceof Date) return `'${v.toISOString().slice(0, 19).replace('T', ' ')}'`;
  if (Buffer.isBuffer(v)) return v.length ? `0x${v.toString('hex')}` : "''";
  if (typeof v === 'number') return String(v);
  return db.escape(String(v));
};

const insertRows = (table, rows) => {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]).map((c) => `\`${c}\``).join(', ');
  const values = rows.map((r) => `(${Object.values(r).map(sqlValue).join(', ')})`).join(',\n  ');
  return `INSERT INTO \`${table}\` (${cols}) VALUES\n  ${values};\n\n`;
};

(async () => {
  // ---- schema.sql ----
  const [tables] = await db.query(
    "SELECT TABLE_NAME AS name FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME"
  );
  let schema = header('SBO database schema') + 'SET FOREIGN_KEY_CHECKS = 0;\n\n';
  for (const { name } of tables) {
    const [[row]] = await db.query(`SHOW CREATE TABLE \`${name}\``);
    schema += `${row['Create Table'].replace(/ AUTO_INCREMENT=\d+/, '')};\n\n`;
  }
  schema += 'SET FOREIGN_KEY_CHECKS = 1;\n';
  fs.writeFileSync(path.join(OUT_DIR, 'schema.sql'), schema);

  // ---- seed-reference.sql ----
  let seed = header('SBO reference data') + 'SET FOREIGN_KEY_CHECKS = 0;\n\n';
  for (const table of REFERENCE_TABLES) {
    const [rows] = await db.query(`SELECT * FROM \`${table}\``);
    seed += insertRows(table, rows);
  }

  // Shops: their locations and addresses (business addresses only).
  const [locations] = await db.query('SELECT * FROM location');
  const [shopAddresses] = await db.query('SELECT * FROM address WHERE addressID IN (?)', [locations.map((l) => l.addressID)]);
  seed += insertRows('address', shopAddresses) + insertRows('location', locations);
  seed += insertRows('store', (await db.query('SELECT * FROM store'))[0]);

  // House broker with a synthetic contact (the legacy dump links it to a real person).
  const [[broker]] = await db.query('SELECT * FROM broker WHERE brokerID = ?', [HOUSE.brokerID]);
  const [[city]] = await db.query('SELECT cityID FROM address WHERE addressID = ?', [shopAddresses[0].addressID]);
  seed += insertRows('address', [{ addressID: HOUSE.addressID, cityID: city.cityID, email: 'contact@example.com' }]);
  seed += insertRows('broker', [{ ...broker, addressID: HOUSE.addressID }]);
  seed += `INSERT INTO \`contact\` (\`contactID\`, \`addressID\`, \`firstName\`, \`lastName\`, \`username\`, \`password\`, \`email\`) VALUES\n` +
    `  ('${HOUSE.contactID}', '${HOUSE.addressID}', 'SBO', 'Achats', 'sbo_achats', '!disabled', 'contact@example.com');\n\n`;
  seed += insertRows('brokercontact', [{ brokerID: HOUSE.brokerID, contactID: HOUSE.contactID, startedDate: new Date('2026-01-01T00:00:00Z'), endedDate: null }]);

  seed += 'SET FOREIGN_KEY_CHECKS = 1;\n';
  fs.writeFileSync(path.join(OUT_DIR, 'seed-reference.sql'), seed);

  console.log(`Wrote schema.sql (${tables.length} tables) and seed-reference.sql (${(seed.length / 1024).toFixed(0)} KB)`);
  await db.end();
})().catch((e) => { console.error(e.message); process.exit(1); });
